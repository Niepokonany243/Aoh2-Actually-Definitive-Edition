    public final void addVassal(int iCivID) {
        for (int i = 0; i < this.iVassalsSize; ++i) {
            if (this.vassals.get(i).iCivID != iCivID) continue;
            return;
        }
        this.vassals.add(new Vassal_GameData(iCivID));
        this.iVassalsSize = this.vassals.size();
    }

    public final void removeVassal(int iCivID) {
        for (int i = 0; i < this.iVassalsSize; ++i) {
            if (this.vassals.get(i).iCivID != iCivID) continue;
            this.vassals.remove(i);
            this.iVassalsSize = this.vassals.size();
            return;
        }
    }

